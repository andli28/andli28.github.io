// The 20 jobs. A tile is one tool call the model wants to make:
//   tool   which tool it calls
//   size   cells its result takes in the window
//   gem    the fact in that result (a letter); `at` says where it sits
//          (head / tail / mid) and `exact` marks a detail summaries lose
//   needs  gems that must be in the window before this call
//   hide   the player learns this tile's secret by watching a run
//
// `pre` chips are part of the level and can't be moved. `tray` is what the
// player may place. `demo` chips place themselves on worked-example levels.
// Support fades through each chapter: worked → complete → solo.

const t = (tool, size, o = {}) => ({ tool, size, ...o });
const bot = (...chips) => chips.map(chip => ({ chip, at: "bot", lock: true }));

// "trim@t0:1" → { chip: "trim", at: "t0", set: 1 }
const S = str =>
  str.split(" ").map(x => {
    const [chip, rest] = x.split("@");
    const [at, set] = rest.split(":");
    return { chip, at, set: +(set || 0) };
  });

