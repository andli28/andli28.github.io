for (const j of JOBS) {
  const [done, ...lines] = TEXT[j.id];
  j.done = done;
  j.steps = j.steps.map((s, i) => {
    const t = lines[i];
    return t == null
      ? s
      : Array.isArray(t)
        ? { ...s, q: t[0], a: t[1] }
        : { ...s, q: t };
  });
}

const met = new Set();
for (const j of JOBS) {
  j.gives = j.sol.filter(id => !met.has(id));
  j.sol.forEach(id => met.add(id));
}
