// The jobs. Each is a request plus the steps the model wants to take.
//
//   c(tool, size, {...})  a tool call: `fact` it yields, facts it `needs`,
//                         `risky` ("danger" | "outside"), `hostile`, `easy`,
//                         `dull`, `explore`, `at: "mid"`, `once`
//   e({...})              an edit; `bad` is the kind of bug it introduces
//   user / sleep / quit   a follow-up message, the session ending, the model
//                         deciding it has done enough
//   write                 the result has to land in a file
//
// `lore` is know-how the model doesn't have: which parts can supply it, and
// how many cells it takes when stuffed into the prompt. `tier` sets how much
// the failure line gives away: 0 guided, 1 names the part, 2 names the branch.

const c = (tool, size, o = {}) => ({ t: "call", tool, size, ...o });
const e = (o = {}) => ({ t: "call", tool: "tools", size: 1, edit: true, ...o });
const user = (o = {}) => ({ t: "user", ...o });
const write = (o = {}) => ({ t: "write", ...o });
const sleep = { t: "sleep" };
const quit = { t: "quit" };

